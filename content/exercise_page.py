def build(B, chs):
    esc = B.esc
    B.USED.update({('doc', 'judge'), ('fly', 'magnify'), ('asst', 'smile')})
    o = [B.head('연습 문제 — ' + B.SERIES, '장마다 계산 문제 2개. 숫자를 직접 입력해 채점하고, 단계별 풀이와 흔한 실수를 확인해요.', depth=1, og='../img/og/og_index.webp')]
    o.append('<nav class="top" aria-label="연습 문제 목차"><a class="logo" href="../index.html">%s</a>%s<a href="#score">점수</a></nav><div id="prog"></div>' % (
        B.LOGO, ''.join('<a href="#ex%02d">%02d</a>' % (c['no'], c['no']) for c in chs)))
    o.append('<header class="hero"><div class="wrap"><div class="kicker">연습 · 계산 문제 18개</div><h1>연습 문제 — 직접 계산해 보기</h1>'
             '<p class="q">핵심 질문 — 고르기가 아니라 숫자를 직접 내면, 어디서 막히는지 보일까?</p>'
             '<p>장마다 계산 문제 2개예요. 상자에 숫자를 넣고 「채점」을 누르면 바로 맞는지 알려 주고, 단계별 풀이와 초파리의 흔한 실수, 업무에서 쓰는 곳을 보여 줘요. 문제의 숫자는 모두 설명용 예시값이에요. 점수는 이 화면에만 보이고 어디에도 저장하지 않아요.</p>'
             + B.says([('doc', 'front', '계산기를 써도 괜찮아요. 중요한 건 「왜 그 식인가」예요. 틀리면 풀이를 펼쳐 한 줄씩 비교해 보세요.'),
                       ('asst', 'smile', '저는 2장 2번에서 행렬 자리 수를 답했다가 틀렸어요. 여러분은 어떨까요?')]) + '</div></header>')
    o.append('<section class="level"><div class="wrap" id="exroot">')
    data = {}
    for c in chs:
        n = c['no']
        items = EX[n]
        o.append('<div class="panel exch" id="ex%02d"><div class="ptitle">%02d장 · %s</div>' % (n, n, esc(c['title'])))
        for k, (q, a, unit, steps, miss, work) in enumerate(items, 1):
            pid = 'p%02d_%d' % (n, k)
            data[pid] = a
            o.append('<div class="exq" data-id="%s"><p><b>문제 %d.</b> %s</p>'
                     '<div class="ctrl"><label class="glabel" for="in_%s">답</label><input id="in_%s" inputmode="decimal" type="text" style="width:9em" aria-describedby="fb_%s"> %s '
                     '<button type="button" class="bt exgo">채점</button></div><p class="exfb" id="fb_%s" aria-live="polite"></p>'
                     '<details><summary>단계별 풀이 보기</summary><ol>%s</ol><p class="r"><b>초파리의 흔한 실수</b> — %s</p><p class="g"><b>업무에서는</b> — %s</p></details></div>' % (
                         pid, k, esc(q), pid, pid, pid, esc(unit), pid, ''.join('<li>%s</li>' % esc(s) for s in steps), esc(miss), esc(work)))
        o.append('<p class="note exsc" data-ch="%02d">이 장 점수: 아직 채점 전 · <a href="../%s.html">%02d장 다시 보기</a></p></div>' % (n, c['slug'], n))
    o.append('</div></section>')
    o.append('<section class="level" id="score"><div class="wrap"><h2>전체 점수</h2><p id="extotal" class="insight" aria-live="polite">아직 채점한 문제가 없어요.</p>'
             '<p class="note">장 점수가 70% 아래면 그 장의 「한눈에 보는 정리」와 수식 상자를 다시 보는 것을 권해요. 다시 풀어도 괜찮아요. 점수는 저장되지 않아요.</p></div></section>')
    o.append(B.footer_html(('../index.html', '오리엔테이션으로'), ('../practice/index.html', '마지막 장 · 실전 연습장'), ''))
    o.append('<script>window.EXANS=%s;</script>' % json.dumps(data))
    o.append('<script src="../assets/sprites.js"></script><script src="../assets/lab.js"></script><script src="../assets/exercise.js"></script></body></html>')
    os.makedirs(os.path.join(B.ROOT, 'exercise'), exist_ok=True)
    open(os.path.join(B.ROOT, 'exercise', 'index.html'), 'w', encoding='utf-8').write('\n'.join(o))
    print('built exercise')
